"""Maintain requirement navigation while preserving authored Markdown.

``lint_indexes`` creates indexes at the tiers root, configured level folders,
and every ancestor of a requirement. Only a delimited navigation block is owned
by the generator; introductory prose, frontmatter and log.md remain authored.
"""

from __future__ import annotations

import difflib
from pathlib import Path
from urllib.parse import quote

from okf_schema.okfreq.core import (
    RequirementError,
    _atomic_write,
    load_config,
    load_requirements,
    tiers_path,
)

# @implements_req SwRS-OKFSCHEMA-OKFREQ-009

_START = "<!-- okfreq:index:start -->"
_END = "<!-- okfreq:index:end -->"


def _label(text: str) -> str:
    """Keep one metadata value on a single escaped Markdown line."""
    return " ".join(text.split()).replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def lint_indexes(
    root: Path,
    *,
    check: bool = False,
    show_diff: bool = False,
) -> list[Path]:
    """Refresh generated requirement navigation without rewriting authored content.

    .. versionadded:: 0.13.0

    Args:
        root:
            Requirements bundle root containing config.yml.
        check:
            Report stale indexes without writing.
        show_diff:
            Print unified diffs without writing.

    Returns:
        Index paths changed or requiring changes, sorted by path.

    Raises:
        RequirementError:
            If generated-block delimiters are malformed or a configured level
            folder escapes the tiers root.

    Examples:
        Preview navigation from a project script::

            stale = lint_indexes(Path("requirements"), check=True)
    """
    tiers = tiers_path(root).resolve()
    documents = load_requirements(root)
    directories = {tiers}
    for level in load_config(root)["levels"].values():
        directory = (tiers / str(level["folder"])).resolve()
        if not directory.is_relative_to(tiers):
            raise RequirementError(f"level folder escapes tiers root: {directory}")
        directories.add(directory)
        directories.update(parent for parent in directory.parents if parent.is_relative_to(tiers))
    for path, _, _ in documents.values():
        directory = path.parent.resolve()
        if not directory.is_relative_to(tiers):
            raise RequirementError(f"requirement escapes tiers root: {path}")
        directories.add(directory)
        directories.update(parent for parent in directory.parents if parent.is_relative_to(tiers))

    # An emptied scope may still contain an index we own. Refresh it too,
    # otherwise deleting its last requirement leaves a stale link behind.
    for index in tiers.rglob("index.md"):
        if any(part in {"_schema", "guidelines"} for part in index.relative_to(tiers).parts):
            continue
        if _START not in index.read_text(encoding="utf-8"):
            continue
        directory = index.parent.resolve()
        if not directory.is_relative_to(tiers):
            raise RequirementError(f"index directory escapes tiers root: {index}")
        directories.add(directory)
        directories.update(parent for parent in directory.parents if parent.is_relative_to(tiers))

    # Plan every update before writing: an invalid marker in one index must
    # not leave the other indexes partially regenerated.
    changes: list[tuple[Path, str, str]] = []
    for directory in sorted(directories):
        index = directory / "index.md"
        original = index.read_text(encoding="utf-8") if index.exists() else ""
        lines = [
            _START,
            "<!-- Generated by okfreq lint; edit requirement metadata instead. -->",
            "",
        ]
        for child in sorted(directories):
            if child.parent == directory:
                lines.append(f"- [{_label(child.name)}]({quote(child.name, safe='')}/index.md)")
        for identifier, (path, data, _) in sorted(documents.items()):
            if path.parent.resolve() == directory:
                title = _label(str(data.get("title", identifier)))
                description = _label(str(data.get("description", "")))
                suffix = f" — {description}" if description else ""
                lines.append(
                    f"- [{_label(identifier)} — {title}]({quote(path.name, safe='')}){suffix}"
                )
        if len(lines) == 3:
            lines.append("No requirements in this directory.")
        lines.extend(["", _END])
        block = "\n".join(lines)
        if _START in original or _END in original:
            if original.count(_START) != 1 or original.count(_END) != 1:
                raise RequirementError(f"{index}: expected one complete generated index block")
            start, end = original.index(_START), original.index(_END)
            if start >= end:
                raise RequirementError(f"{index}: generated index delimiters are reversed")
            rendered = original[:start] + block + original[end + len(_END) :]
        else:
            prefix = original or (
                "# Requirements\n" if directory == tiers else f"# {directory.name}\n"
            )
            separator = "" if prefix.endswith("\n\n") else "\n" if prefix.endswith("\n") else "\n\n"
            rendered = prefix + separator + block + "\n"
        if rendered != original:
            changes.append((index, original, rendered))

    for path, original, rendered in changes:
        if show_diff:
            print(
                "".join(
                    difflib.unified_diff(
                        original.splitlines(True),
                        rendered.splitlines(True),
                        fromfile=str(path),
                        tofile=str(path),
                    )
                )
            )
        elif not check:
            _atomic_write(path, rendered)
    return [path for path, _, _ in changes]
